// @ts-check
// Embeds wordpress-plugin/localdock-companion/**/*.php into a TS module so the
// extension can upload the plugin to a remote site over SFTP. wordpress-plugin/
// is excluded from the packaged .vsix (see .vscodeignore) and is never compiled
// by esbuild — this script is the only bridge between that PHP source and the
// bundled extension. Re-run after editing any file under wordpress-plugin/.
const fs = require('fs');
const path = require('path');

const SOURCE_DIR = path.join(__dirname, '..', 'wordpress-plugin', 'localdock-companion');
const OUTPUT_FILE = path.join(__dirname, '..', 'src', 'companion', 'companionPluginFiles.generated.ts');

function walk(dir, base) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walk(fullPath, base));
    } else if (entry.name.endsWith('.php')) {
      const relativePath = path.relative(base, fullPath).split(path.sep).join('/');
      files.push({ relativePath, content: fs.readFileSync(fullPath, 'utf-8') });
    }
  }
  return files;
}

function extractVersion(files) {
  const mainFile = files.find((f) => f.relativePath === 'localdock-companion.php');
  if (!mainFile) {
    throw new Error('Could not find localdock-companion.php to extract LOCALDOCK_COMPANION_VERSION from');
  }
  const match = mainFile.content.match(/define\(\s*'LOCALDOCK_COMPANION_VERSION',\s*'([^']+)'\s*\)/);
  if (!match) {
    throw new Error('Could not find LOCALDOCK_COMPANION_VERSION constant in localdock-companion.php');
  }
  return match[1];
}

function main() {
  const files = walk(SOURCE_DIR, SOURCE_DIR).sort((a, b) => a.relativePath.localeCompare(b.relativePath));
  const version = extractVersion(files);

  const entries = files
    .map(({ relativePath, content }) => `  ${JSON.stringify(relativePath)}: ${JSON.stringify(content)},`)
    .join('\n');

  const output = `// AUTO-GENERATED by scripts/generate-companion-plugin-source.js — do not edit by hand.
// Source of truth: wordpress-plugin/localdock-companion/. Re-run the generator
// after editing plugin PHP: node scripts/generate-companion-plugin-source.js

export const COMPANION_PLUGIN_VERSION = ${JSON.stringify(version)};

export const COMPANION_PLUGIN_FILES: Record<string, string> = {
${entries}
};
`;

  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, output, 'utf-8');
  console.log(`[generate-companion-plugin-source] Wrote ${files.length} file(s) to ${path.relative(process.cwd(), OUTPUT_FILE)}`);
}

main();
